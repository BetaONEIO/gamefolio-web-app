import { toGameSlug } from '../../shared/game-routes';

interface SlugGame {
  id: number;
  name: string;
  isApproved: boolean;
  isUserAdded: boolean;
  twitchId: string | null;
}

type GameSlugMatch<T> =
  | { status: 'found'; game: T }
  | { status: 'missing' | 'unavailable' };

function compactSlug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]/g, '');
}

function chooseCatalogueGame<T extends SlugGame>(games: T[]): T | undefined {
  const approved = games.filter(game => game.isApproved);
  // A custom duplicate must not displace an established catalogue entry.
  const catalogue = approved.filter(game => !game.isUserAdded);
  const candidates = catalogue.length ? catalogue : approved;
  const providerBacked = candidates.filter(game => game.twitchId?.trim());
  if (new Set(providerBacked.map(game => game.twitchId)).size > 1) {
    // Different provider IDs can be different releases sharing a title/URL.
    // Preserve the existing catalogue order until those URLs are disambiguated.
    return providerBacked[0];
  }
  return (providerBacked.length ? providerBacked : candidates)
    .sort((a, b) => a.id - b.id)[0];
}

/** Resolve the same slug generated by publicGamePath before considering old compact links. */
export function findGameBySlug<T extends SlugGame>(games: T[], slug: string): GameSlugMatch<T> {
  const compact = compactSlug(slug);
  if (!compact) return { status: 'unavailable' };

  const exactSlug = toGameSlug(slug);
  let candidates = games.filter(game => toGameSlug(game.name) === exactSlug);
  if (!candidates.length) {
    candidates = games.filter(game => compactSlug(game.name) === compact);
    if (!candidates.length) return { status: 'missing' };
    // V.O.I.D and Void, for example, have distinct current URLs. A legacy
    // compact URL cannot tell us which one was intended.
    if (new Set(candidates.map(game => toGameSlug(game.name))).size > 1) {
      return { status: 'unavailable' };
    }
  }

  const game = chooseCatalogueGame(candidates);
  return game ? { status: 'found', game } : { status: 'unavailable' };
}

interface ProviderGame {
  id: string;
  name: string;
  box_art_url: string;
}

interface GameSlugDependencies<T extends SlugGame> {
  getAllGames(): Promise<T[]>;
  searchGames(query: string): Promise<ProviderGame[]>;
  createGame(data: { name: string; imageUrl: string; twitchId: string }): Promise<T>;
}

export async function resolveGameBySlug<T extends SlugGame>(
  slug: string,
  dependencies: GameSlugDependencies<T>,
): Promise<T | null> {
  const games = await dependencies.getAllGames();
  const match = findGameBySlug(games, slug);
  if (match.status === 'found') return match.game;
  // Do not recreate rejected games or guess between ambiguous local matches.
  if (match.status === 'unavailable') return null;

  const providerGames = await dependencies.searchGames(slug.replace(/-/g, ' '));
  const providerGame = providerGames.find(game => toGameSlug(game.name) === toGameSlug(slug));
  if (!providerGame) return null;

  // Provider names can change. Reuse the saved ID and retain its approval state.
  const existing = games.filter(game => game.twitchId === providerGame.id);
  if (existing.length) return chooseCatalogueGame(existing) ?? null;

  return dependencies.createGame({
    name: providerGame.name,
    imageUrl: providerGame.box_art_url.replace('{width}x{height}', '600x800'),
    twitchId: providerGame.id,
  });
}
